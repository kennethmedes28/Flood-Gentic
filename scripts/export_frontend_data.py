"""Write the evacuation centers and the emergency hotlines as built-in data files for the frontend pages and the backend.

    cd backend && uv run python ../scripts/export_frontend_data.py            # write the files
    cd backend && uv run python ../scripts/export_frontend_data.py --check    # fail if they are out of date

The files written:

    frontend/src/data/evacuation-centers.ts   from datasets/ncr_evacuation_centers.csv
    frontend/src/data/emergency-contacts.ts   from corpus/ph_emergency_contacts.csv
    backend/agents/reference_data.py          from both: the hotlines and the barangay names the chat agents use

The backend does not read any CSV file at run time. Emergency numbers must never depend on the network or the database, so the
agents use this built-in copy (the Supabase tables are filled from the same CSV files by sync_datasets_to_supabase.py).

Every value is copied exactly as it is in the CSV. Phone numbers in particular are never reformatted or
rebuilt: a wrong digit can cost a life. The only thing worked out here is which cities a local hotline belongs to,
by finding a city name in the agency name ("Pasig City Rescue" belongs to Pasig City). Hospitals do not name
their city, so they get none.

Run it again whenever one of the two CSV files changes, and commit the result.
"""

import argparse
import csv
import json
import pprint
import sys
import unicodedata
from pathlib import Path

REPO_DIR = Path(__file__).resolve().parent.parent
CENTERS_CSV = REPO_DIR / "datasets" / "ncr_evacuation_centers.csv"
CONTACTS_CSV = REPO_DIR / "corpus" / "ph_emergency_contacts.csv"
OUT_DIR = REPO_DIR / "frontend" / "src" / "data"
BACKEND_DATA = REPO_DIR / "backend" / "agents" / "reference_data.py"

# Only these hotline groups belong to a city. The others are national, or hospitals (which name no city).
LOCAL_CATEGORIES = {"Local - City Rescue", "Local - Fire"}

HEADER = (
    "// GENERATED by scripts/export_frontend_data.py from {source}.\n"
    "// Do not edit by hand: change the CSV and run the script again.\n\n"
)


def read_csv(path: Path) -> list[dict]:
    """Rows of a CSV file. utf-8-sig drops the byte-order mark some files start with."""
    with open(path, newline="", encoding="utf-8-sig") as file:
        return list(csv.DictReader(file))


def plain(text: str) -> str:
    """Lower-case text without accents, so "Parañaque" matches "paranaque"."""
    decomposed = unicodedata.normalize("NFKD", text.lower())
    return "".join(character for character in decomposed if not unicodedata.combining(character))


def city_name_key(city: str) -> str:
    """The part of a city's name used to find it in an agency name: "Pasig City" -> "pasig"."""
    return plain(city.removesuffix(" City"))


def build_centers(rows: list[dict]) -> tuple[list[dict], list[str]]:
    """The centers as the frontend uses them, and the sorted list of cities."""
    centers = [
        {
            "id": f"{row['city']}|{row['barangay']}|{row['name']}",  # the database keeps these three unique
            "city": row["city"],
            "barangay": row["barangay"],
            "name": row["name"],
            "type": row["type"],
            "status": row["status_in_source"],
            "source": row["source"],
            "lat": float(row["latitude"]),
            "lng": float(row["longitude"]),
            "notes": row["notes"],
        }
        for row in rows
    ]
    return centers, sorted({center["city"] for center in centers})


def build_contacts(rows: list[dict], cities: list[str]) -> list[dict]:
    """The hotlines as the frontend uses them. Local ones list the cities found in the agency name."""
    keys = {city: city_name_key(city) for city in cities}
    contacts = []
    for row in rows:
        agency = plain(row["Agency"])
        matched = [city for city, key in keys.items() if key in agency] if row["Category"] in LOCAL_CATEGORIES else []
        contacts.append(
            {
                "agency": row["Agency"],
                "category": row["Category"],
                "type": row["Contact Type"],
                "number": row["Number"],
                "notes": row["Notes"],
                "cities": matched,
            }
        )
    return contacts


def as_typescript(source: str, declarations: str) -> str:
    return HEADER.format(source=source) + declarations


def json_block(value) -> str:
    return json.dumps(value, ensure_ascii=False, indent=2)


def build_backend_data() -> str:
    """The Python module with the hotlines (rows exactly as in the CSV) and each barangay that has an evacuation center."""
    contact_rows = [
        {name: row[name] for name in ("Agency", "Category", "Contact Type", "Number", "Notes")} for row in read_csv(CONTACTS_CSV)
    ]
    places = sorted({(row["city"], row["barangay"]) for row in read_csv(CENTERS_CSV)})
    return (
        HEADER.format(source="corpus/ph_emergency_contacts.csv and datasets/ncr_evacuation_centers.csv").replace("//", "#")
        + '"""Built-in reference data for the chat agents: emergency hotlines and the barangays that have evacuation centers.\n\n'
        + "Numbers are copied exactly as written in the list: a wrong digit can cost a life.\n"
        + '"""\n\n'
        + f"CONTACT_ROWS: list[dict[str, str]] = {pprint.pformat(contact_rows, width=140, sort_dicts=False)}\n\n"
        + f"# (city, barangay) of every evacuation center, as written in the list.\n"
        + f"EVACUATION_CENTER_PLACES: list[tuple[str, str]] = {pprint.pformat(places, width=140)}\n"
    )


def build_files() -> dict[Path, str]:
    """The text of each file to write, by path."""
    centers, cities = build_centers(read_csv(CENTERS_CSV))
    contacts = build_contacts(read_csv(CONTACTS_CSV), cities)

    centers_ts = as_typescript(
        "datasets/ncr_evacuation_centers.csv",
        "export type EvacuationCenter = {\n"
        "  /** Unique: city, barangay and name together. */\n"
        "  id: string\n  city: string\n  barangay: string\n  name: string\n  type: string\n"
        "  /** How the center is known to be in use or designated, as written in the source list. */\n"
        "  status: string\n  /** The list or report the center comes from. */\n  source: string\n"
        "  lat: number\n  lng: number\n  notes: string\n}\n\n"
        f"/** The cities that have centers, sorted. */\nexport const NCR_CITIES: string[] = {json_block(cities)}\n\n"
        f"export const EVACUATION_CENTERS: EvacuationCenter[] = {json_block(centers)}\n",
    )
    contacts_ts = as_typescript(
        "corpus/ph_emergency_contacts.csv",
        "export type Contact = {\n  agency: string\n  category: string\n  /** Hotline, Landline, Mobile, Text, and so on. */\n  type: string\n"
        "  /** Exactly as written in the list: it can be a range such as \"(02) 8882-4151 to 77\" or an instruction. */\n  number: string\n"
        "  notes: string\n  /** The cities a local hotline serves; empty for national hotlines and hospitals. */\n  cities: string[]\n}\n\n"
        f"export const EMERGENCY_CONTACTS: Contact[] = {json_block(contacts)}\n",
    )
    return {
        OUT_DIR / "evacuation-centers.ts": centers_ts,
        OUT_DIR / "emergency-contacts.ts": contacts_ts,
        BACKEND_DATA: build_backend_data(),
    }


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    parser.add_argument("--check", action="store_true", help="write nothing; exit 1 if a file is missing or out of date")
    args = parser.parse_args()

    files = build_files()
    stale = [path for path, text in files.items() if not path.exists() or path.read_text(encoding="utf-8") != text]

    if args.check:
        for path in stale:
            print(f"Out of date: {path.relative_to(REPO_DIR)}")
        print("The frontend data is up to date." if not stale else "Run the script without --check to update it.")
        return 1 if stale else 0

    for path, text in files.items():
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(text, encoding="utf-8")
        print(f"Wrote {path.relative_to(REPO_DIR)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
